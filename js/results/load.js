/**
 * results/load.js — reads a finished analysis back into the studio.
 *
 * OpenSees writes recorder files as bare columns of numbers. `manifest.json`,
 * written by the same script, says what each column is; everything here is
 * driven by that file rather than by re-deriving the tag scheme, so a result
 * set opened a year later still lines up with the model that produced it.
 */

/** Files that are numeric tables rather than JSON. */
const isTable = (name) => name.endsWith('.out') || name.endsWith('.txt');

export class ResultError extends Error {
  constructor(message) {
    super(message);
    this.name = 'ResultError';
  }
}

/**
 * Builds a result set from the files the user handed over.
 *
 * @param {File[]|FileList} fileList  everything from the output directory
 * @returns {Promise<object>} the loaded result set
 */
export async function loadResults(fileList) {
  const files = [...fileList];
  if (!files.length) throw new ResultError('No files were selected.');

  const manifestFile = files.find((f) => baseName(f) === 'manifest.json');
  if (!manifestFile) {
    throw new ResultError(
      'manifest.json is missing. Run a script generated by version 1.1 or later — '
      + 'without the manifest the columns in the .out files cannot be identified.'
    );
  }

  let manifest;
  try {
    manifest = JSON.parse(await manifestFile.text());
  } catch {
    throw new ResultError('manifest.json could not be parsed.');
  }
  if (!manifest || typeof manifest !== 'object' || !manifest.files) {
    throw new ResultError('manifest.json is not an OpenSees Model Studio manifest.');
  }

  const series = {};
  const missing = [];      // never handed over
  const empty = [];        // handed over, but with nothing readable in them

  for (const [name, spec] of Object.entries(manifest.files)) {
    if (!isTable(name)) continue;
    const file = files.find((f) => baseName(f) === name);
    if (!file) { missing.push(name); continue; }

    const width = spec.columns.length;
    const rows = parseTable(await file.text(), width);
    if (!rows.length) { empty.push(name); continue; }
    series[name] = { ...spec, name, width, rows };
  }

  // Saying "nothing was found" without saying what was looked for is no help at
  // all, and the two ways this fails need different answers from the user.
  if (!Object.keys(series).length) {
    const listed = Object.keys(manifest.files).filter(isTable);
    if (empty.length) {
      throw new ResultError(
        `${empty.length} of the ${listed.length} result files are empty: ${empty.join(', ')}. `
        + 'OpenSees flushes its recorders when the script finishes, so this usually means the '
        + 'analysis stopped part way — check the console output of the run.'
      );
    }
    throw new ResultError(
      `None of the ${listed.length} files the manifest lists were selected. It expects `
      + `${listed.join(', ')} — drop the whole output folder, or select every file in it `
      + '(Ctrl+A in the file dialog), not just manifest.json.'
    );
  }

  return index(manifest, series, [...missing, ...empty]);
}

/** A dropped directory gives paths like `output/node_disp.out`. */
function baseName(file) {
  const path = file.webkitRelativePath || file.name;
  return path.slice(path.lastIndexOf('/') + 1);
}

/**
 * Parses whitespace-separated numbers into fixed-width rows.
 * A trailing partial row — a run killed mid-write — is dropped rather than
 * being padded, because a half-written step is not a step.
 */
export function parseTable(text, width) {
  const rows = [];
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    const parts = trimmed.split(/\s+/);
    if (parts.length < width) continue;

    const row = new Float64Array(width);
    let ok = true;
    for (let i = 0; i < width; i++) {
      const v = Number(parts[i]);
      if (!Number.isFinite(v)) { ok = false; break; }
      row[i] = v;
    }
    if (ok) rows.push(row);
  }
  return rows;
}

/* ────────────────────────────── indexing ────────────────────────────── */

/** Wraps the raw manifest and tables in the lookups every panel needs. */
function index(manifest, series, missing) {
  const nodes = new Map((manifest.nodes || []).map((n) => [n.tag, n]));
  const elements = new Map((manifest.elements || []).map((e) => [e.tag, e]));
  const stories = [...(manifest.stories || [])].sort((a, b) => a.level - b.level);

  // Column lookups, built once: a time history over a hundred nodes is tens of
  // thousands of columns and a linear scan per query would be felt.
  const nodeColumns = new Map();     // `${file}|${tag}|${dof}` → column index
  const elementColumns = new Map();  // `${file}|${tag}|${component}` → column index

  for (const [file, spec] of Object.entries(series)) {
    spec.columns.forEach((col, i) => {
      if (col.node !== undefined) nodeColumns.set(`${file}|${col.node}|${col.dof}`, i);
      else if (col.element !== undefined) elementColumns.set(`${file}|${col.element}|${col.component}`, i);
      else if (col.name) spec[`col_${col.name}`] = i;
    });
  }

  const results = {
    manifest,
    series,
    missing,
    nodes,
    elements,
    stories,
    cases: manifest.cases || {},
    units: manifest.units || {},
    supports: manifest.supports || [],

    /** Column index of one node's DOF in a file, or -1. */
    nodeColumn(file, tag, dof) {
      const i = nodeColumns.get(`${file}|${tag}|${dof}`);
      return i === undefined ? -1 : i;
    },

    /** Column index of one element component in a file, or -1. */
    elementColumn(file, tag, component) {
      const i = elementColumns.get(`${file}|${tag}|${component}`);
      return i === undefined ? -1 : i;
    },

    /** The whole time column of a series, or step numbers when there is none. */
    time(file) {
      const spec = series[file];
      if (!spec) return [];
      if (spec.col_time === undefined) return spec.rows.map((_, i) => i + 1);
      return spec.rows.map((r) => r[spec.col_time]);
    },

    /** One column as a plain array. */
    column(file, i) {
      const spec = series[file];
      if (!spec || i < 0) return [];
      return spec.rows.map((r) => r[i]);
    },

    has(file) { return !!series[file]; },
    steps(file) { return series[file] ? series[file].rows.length : 0; },
  };

  results.modeShapes = readModeShapes(results);
  return results;
}

/**
 * `mode_shapes.out` is one row per node per mode rather than a time series, so
 * it is folded into a map of mode → node → displacement once on load.
 */
function readModeShapes(results) {
  const spec = results.series['mode_shapes.out'];
  if (!spec) return null;

  const byMode = new Map();
  for (const row of spec.rows) {
    const [mode, tag, ux, uy, uz] = row;
    if (!byMode.has(mode)) byMode.set(mode, new Map());
    byMode.get(mode).set(tag, [ux, uy, uz]);
  }
  return byMode;
}
